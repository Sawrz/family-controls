export type Message = keyof typeof messages;
export function translate(language: Language, key: Message): string {
  return messages[key][language === 'de' ? 1 : 0];
}
export function actionLabel(language: Language, action: string): string {
  return action in messages ? translate(language, action as Message) : action;
}
export function dateTime(language: Language, value: string | null, timezone?: string): string {
  if (!value) return translate(language, 'neverSeen');
  return new Intl.DateTimeFormat(language, {
    dateStyle: 'short',
    timeStyle: 'short',
    timeZone: timezone,
  }).format(new Date(value));
}
