"""Small dependency contracts used by the application."""

from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol

from .domain import Observation, Policy, State


class Clock(Protocol):
    def now(self) -> datetime: ...
    def monotonic(self) -> float: ...


class Enforcement(Protocol):
    def observe(self, user: str) -> Observation: ...
    def validate(self, policy: Policy) -> None: ...
    def apply(self, user: str, policy: Policy, now: datetime) -> None: ...
    def restore(self) -> None: ...


class AgentGateway(Protocol):
    def authorize(self, actor: str) -> dict: ...
    def history(self, child: str) -> list[dict]: ...
    def status(self, child: str) -> dict: ...
    def command(
        self, child: str, action: str, payload: dict, operation: str, actor: str
    ) -> dict: ...


class StateRepository(Protocol):
    def transaction(self) -> AbstractContextManager[None]: ...
    def load(self, user: str, now: datetime) -> State: ...
    def save(self, user: str, state: State) -> None: ...
    def operation(self, operation: str) -> tuple[str, str] | None: ...
    def record(
        self, operation: str, user: str, fingerprint: str, revision: int, now: datetime
    ) -> None: ...
    def audit(self, user: str, action: str, details: dict, now: datetime) -> None: ...
    def applied(self, user: str, revision: int, now: datetime, error: str | None) -> None: ...
    def application_status(self, user: str) -> dict: ...
    def history(self, user: str, limit: int = 20) -> list[dict]: ...


class Sessions(Protocol):
    def all_locked(self, user: str) -> bool: ...
